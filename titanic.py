# 3. Apply the *EXACT SAME* preprocessing
# ---
# (This assumes 'x' is your original *unprocessed* feature DataFrame
# and 'sc' is your *fitted* StandardScaler from training)

# One-hot encode Sex
gender = pd.get_dummies(new_df['Sex'], drop_first=True)
new_df = new_df.drop(['Sex'], axis=1)
