import pandas as pd

df=pd.read_csv("/content/drive/MyDrive/titanic.csv")

df.info()
df.shape

df.isnull().sum()

df.describe().T

med=df['Age'].median()
df['Age'].fillna(med,inplace=True)
mode=df['Embarked'].mode()[0]
df['Embarked'].fillna(mode,inplace=True)

df.drop(['Cabin','Name','PassengerId','Fare','Ticket'],axis=1)
x=df[['Pclass','Age','SibSp','Parch','Embarked','Sex']]

x.columns

y=df['Survived']
y.head()

gender=pd.get_dummies(x['Sex'],drop_first=True)

x=x.drop(['Sex'],axis=1)

x=pd.concat([x,gender],axis=1)
x['family_size']=x['SibSp']+x['Parch']+1

x.head()
x.columns

x=x.drop(['SibSp','Parch'],axis=1)

x = pd.get_dummies(x, columns=['Embarked', 'Pclass'], drop_first=True)
x.head()

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2,random_state=42)

from sklearn.preprocessing import StandardScaler
sc=StandardScaler()
x_train=sc.fit_transform(x_train)
x_test=sc.transform(x_test)

from tensorflow.keras.models import Sequential

from tensorflow.keras.layers import Dense,ReLU,LeakyReLU,Dropout

x.shape

model=Sequential()
model.add(Dense(32, activation='relu'))
# Add dropout for regularization to prevent overfitting
model.add(Dropout(0.2))
# Second hidden layer
model.add(Dense(16, activation='relu'))
# Output layer: 1 neuron with sigmoid activation for binary (0 or 1) classification
model.add(Dense(1, activation='sigmoid'))

# 3. Compile the model
model.compile(optimizer='adam',
              loss='binary_crossentropy', # Best for binary (0/1) classification
              metrics=['accuracy'])

# 4. Train the model
print("\n--- Training Model ---")
history = model.fit(
    x_train,
    y_train,
    epochs=100,           # Number of times to go through the entire dataset
    batch_size=32,      # Number of samples to process before updating weights
    validation_data=(x_test, y_test), # Data to check against after each epoch
    verbose=1           # Set to 0 to silence output during training
)

# 5. Evaluate the model
print("\n--- Evaluating Model ---")
loss, accuracy = model.evaluate(x_test, y_test)
print(f"Test Accuracy: {accuracy*100:.2f}%")
print(f"Test Loss: {loss:.4f}")

